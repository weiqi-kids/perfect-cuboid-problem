def check_in_ideal(expr, quadrics_list, var_list=None):
    """
    Check if expr is in the ideal generated by quadrics_list.
    We do this by reducing expr mod the quadrics.
    For a polynomial, we check if reducing by the Groebner basis gives 0.
    Returns: (is_in_ideal, explanation)
    """
    # Check if expr is a polynomial combination of Q1,Q2,Q3,Q4
    # Simple check: try expr = c1*Q1 + c2*Q2 + c3*Q3 + c4*Q4 for polynomial c_i
    # For degree ≤ 2 linear combinations (no polynomial c_i), just check directly
    # For our maps, the pullback Qi∘φ will be a polynomial; we check if it's in I_V
    # by computing the remainder under Groebner basis.
    # IMPORTANT: we work symbolically so we use polynomial ring over QQ.

    if expr == 0:
        return True, "trivially 0"

    # Try to write as combination
    # For our specific quadrics: Q1,Q2,Q3,Q4 are degree 2.
    # If the pullback Q_i∘φ is also degree ≤ 2, we can try direct comparison.
    # More generally, use polynomial reduction.
    try:
        # Construct the ring and groebner basis
        from sympy import groebner as gb
        vars_used = [a, b, c, d, e, f, g]
        basis = gb(quadrics_list, vars_used, order='lex')
        rem = basis.reduce(expr)[1]
        return rem == 0, f"remainder = {rem}"
    except Exception as ex:
        return None, f"Groebner failed: {ex}"

