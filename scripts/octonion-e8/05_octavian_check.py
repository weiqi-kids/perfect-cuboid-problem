# Define octonion multiplication via the Cayley-Dickson construction:
# Use Fano plane convention from Baez (2002).
# Multiplication table (Baez convention):
#   e_1 e_2 = e_3, e_2 e_3 = e_1, e_3 e_1 = e_2  (i,j,k quaternion)
#   e_1 e_4 = e_5, e_2 e_4 = e_6, e_3 e_4 = e_7
#   e_5 e_6 = e_7? Let me use Cayley-Dickson directly.

# Cayley-Dickson on quaternions H: O = H + l*H where (a + l*b)(c + l*d) =
#   (ac - d_bar b) + l (b c_bar + d a)
# This determines multiplication uniquely.

# Basis: e_0=1, e_1=i, e_2=j, e_3=k=i*j, e_4=l, e_5=l*i, e_6=l*j, e_7=l*k.

# Quaternion multiplication in H (Hamilton): i*j = k, j*k = i, k*i = j.
# e_1*e_2 = e_3
# e_2*e_3 = e_1
# e_3*e_1 = e_2

# Now Cayley-Dickson with l = e_4:
# (a + l b)(c + l d) = (a c - d_bar b) + l(b c_bar + d a)
# where bar is quaternion conjugation: 1_bar=1, i_bar=-i, etc.

# e_4 * e_1 = l * (i + 0) = l*i = e_5
# e_4 * e_2 = l * j = e_6
# e_4 * e_3 = l * k = e_7
# e_1 * e_4 = i * l = ? : (i + l*0)(0 + l*1) = (i*0 - 1_bar*0) + l(0*0_bar + 1*i) = l*i = e_5
# Wait that gives e_1 * e_4 = e_5 as well, but the formula:
#   (a + lb)(c + ld) with a=i, b=0, c=0, d=1:
#     real part: i*0 - 1_bar * 0 = 0  (d_bar = 1_bar = 1, b=0 so this is 0)
#     l part: 0 * c_bar + 1 * i = i
#   So e_1 e_4 = l*i = e_5.
# But octonion are NOT commutative, so we need to check e_4 e_1 carefully:
# e_4 * e_1 = (0 + l*1)(i + l*0) = (0*i - 0_bar*1) + l(1*i_bar + 0*0) = 0 + l*(-i) = -l*i = -e_5
# So e_4 e_1 = -e_5, e_1 e_4 = +e_5.

# So octonions ARE non-commutative. Let me build the full multiplication table.

# Multiplication table for octonions (e_i e_j) for i, j in {1..7}.
# Use the rule: e_i e_j = +/- e_k where (i, j, k) is one of the 7 'lines' in Fano plane.
# Generated by the basic ones (i,j,k as quaternions) plus:
#   e_4 e_1 = -e_5, e_4 e_2 = -e_6, e_4 e_3 = -e_7 (from CD with l=e_4)
#   e_1 e_4 = e_5, e_2 e_4 = e_6, e_3 e_4 = e_7

# Let me compute systematically via CD:
def conj_quat(q):
    """Quaternion conjugate, q is tuple (w,x,y,z)"""
    return (q[0], -q[1], -q[2], -q[3])

def mul_quat(p, q):
    """Hamilton quaternion multiplication"""
    (a, b, c, d) = p
    (e, f, g, h) = q
    return (
        a*e - b*f - c*g - d*h,
        a*f + b*e + c*h - d*g,
        a*g - b*h + c*e + d*f,
        a*h + b*g - c*f + d*e,
    )

def mul_oct(p, q):
    """Octonion multiplication via Cayley-Dickson.
    p, q are tuples of 8 numbers (e_0, ..., e_7).
    Split as p = (a, b) where a, b are quaternions (4-tuples).
    """
    (a0, a1, a2, a3, b0, b1, b2, b3) = p
    (c0, c1, c2, c3, d0, d1, d2, d3) = q
    a = (a0, a1, a2, a3)
    b = (b0, b1, b2, b3)
    c = (c0, c1, c2, c3)
    d = (d0, d1, d2, d3)

    a_c = mul_quat(a, c)
    d_bar = conj_quat(d)
    db_b = mul_quat(d_bar, b)

    b_c_bar = mul_quat(b, conj_quat(c))
    d_a = mul_quat(d, a)

    real_part = tuple(a_c[i] - db_b[i] for i in range(4))
    imag_part = tuple(b_c_bar[i] + d_a[i] for i in range(4))

    return real_part + imag_part

def conj_oct(p):
    """Octonion conjugate: (a, b)^bar = (a_bar, -b)"""
    return (p[0], -p[1], -p[2], -p[3], -p[4], -p[5], -p[6], -p[7])

def norm_oct(p):
    """N(p) = p * p_bar. Returns the real part (norm)."""
    p_bar = conj_oct(p)
    r = mul_oct(p, p_bar)
    # Result should be (N(p), 0, ..., 0)
    return r[0]

