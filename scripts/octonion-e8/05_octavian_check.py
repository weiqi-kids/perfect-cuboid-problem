"""
Octavian (Cayley integer) lattice analysis.

The maximal order of Cayley integers (octavians) in O is, in standard
form, the lattice with basis:
    e_0 = 1
    e_1, e_2, e_3, e_4, e_5, e_6, e_7
together with the 8 "half-integer" elements
    h_0 = (1+e_1+e_2+e_4)/2 + (e_3+e_5+e_6+e_7)/2*0 ...
The standard presentation uses Coxeter's choice with the 'integral cells'.

Concretely (Conway-Smith 'On Quaternions and Octonions', Ch. 9):
The octavians form a lattice isomorphic to E_8 (scaled by sqrt(1/2)
relative to the standard E_8 root lattice — i.e., the minimal norm
of a non-zero octavian is 1, and the lattice has covolume 1/16
which is non-unimodular by a factor of sqrt(2)).

For our PCP analysis, the key question is:
DOES THE PCP VECTOR x = a e_1 + b e_2 + c e_3 + d e_4 + e e_5 + f e_6 + g e_7
LIE IN THE INTEGER LATTICE Z<e_1,...,e_7> OR IN THE OCTAVIAN MAXIMAL ORDER?

Answer: x with integer components a, b, ..., g obviously lies in the
sub-lattice Z<e_1,...,e_7>. The question is whether the OCTAVIAN
factorization theory gives more information than the Lipschitz quaternion
analysis.

Conway-Smith Theorem: Octavians satisfy a NON-ASSOCIATIVE unique
factorization theorem - but FACTORIZATION IS PATH-DEPENDENT (depends on
choice of bracketing).

So the octavian factorization of x.x_bar = N(x) = 4 g^2 may have
RICH STRUCTURE, but extracting an obstruction requires more than just
the norm.

Let's compute concretely:
"""

