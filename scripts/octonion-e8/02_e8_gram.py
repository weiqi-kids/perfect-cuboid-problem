# Halcke 1719 (44, 117, 240, 125, 244, 267, sqrt(73225)~270.6):
a, b, c = 44, 117, 240
d2 = a**2 + b**2; e2 = b**2 + c**2; f2 = a**2 + c**2
d = int(np.sqrt(d2)); e = int(np.sqrt(e2)); f = int(np.sqrt(f2))
g2 = a**2 + b**2 + c**2
print(f"Halcke brick: a={a}, b={b}, c={c}, d={d}, e={e}, f={f}, g^2={g2}")
print(f"  sqrt(g^2) ~ {np.sqrt(g2):.6f}, integer? {int(np.sqrt(g2))**2 == g2}")

# Now build the PCP vector in R^8 (with x_0 = 0; perfect cuboid would have x_8 = g integer):
g_floor = int(np.sqrt(g2))   # not integer for Halcke
# For checking ALL E_8 embeddings, treat g symbolically.

# We construct several candidate sub-lattices of E_8 \otimes Q
# that the PCP problem distinguishes.

# (1) Pythagorean triple sub-lattices:
# Triple (a, b, d) with a^2+b^2=d^2 corresponds to a Gaussian integer
# a+bi in Z[i] of norm d^2. In R^8 / E_8 language:
# vector (a, b, d) lifts to (a,0,0,b,0,0,d,0) (just an example placement).

# Let's think more carefully:
# The 'face Pythagorean structure' has 3 triples sharing pairs:
# T_ab: a^2+b^2=d^2
# T_bc: b^2+c^2=e^2
# T_ac: a^2+c^2=f^2
# T_abc: a^2+b^2+c^2=g^2 (and 2g^2 = d^2+e^2+f^2)

# Define 4 vectors in R^4 (then embed in R^8):
# u_1 = (a, b, 0, -d), N(u_1) = 2(a^2+b^2) [wait, with the sign: a^2+b^2+0+d^2 = 2d^2]
# Hmm, sign doesn't matter for norm. So u_1 = (a, b, 0, d) has N=2d^2.

# More useful: place each triple as a NULL vector in a 4-dim Lorentzian
# style. But we're in positive definite, so let's just see Gram matrices.

# Define the 4 vectors in R^7 (imag octonions):
# Standard basis (e_1..e_7), and look at how PCP solutions decompose.

# Actually the route-W1 file says: 'pure imag octonion
# o = a e_1 + b e_2 + c e_3 + d e_4 + e e_5 + f e_6 + g e_7'
# N(o) = a^2+...+g^2. We have N(o) = 4 g^2.

# So o lies on a 6-sphere of radius 2g in R^7 ⊂ R^8 = O.
