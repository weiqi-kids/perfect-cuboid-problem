# A primitive PCP solution (g, a, b, c, d, e, f) has gcd 1. By the
# parity argument (two-even-one-odd: e.g., a, b even, c odd),
# d = sqrt(a^2+b^2) where a^2+b^2 is divisible by 4 (even + even),
# so d is even. e = sqrt(b^2+c^2) odd^2 + even^2 = odd, so e is odd.
