# E_8 embedding question (Track B from the prompt):
# We embed (a/g, b/g, c/g, d/g, e/g, f/g, 1) into Q^7 ⊂ E_8 ⊗ Q.
# Compute its norm: (a^2+b^2+c^2+d^2+e^2+f^2)/g^2 + 1
#                 = (g^2 + 2g^2)/g^2 + 1 = 3 + 1 = 4.

# So the normalized 7-vector has Q-norm 4 = (2)^2 in the standard
