# Construct Gram matrix of 4 'natural' vectors derived from PCP:
# v1 = (0,a,b,c,d,e,f,g)            # the brick vector
# v2 = (0,b,c,a,e,f,d,g)            # cyclic permutation S_3 action
# v3 = (0,c,a,b,f,d,e,g)            # cyclic S_3
# v4 = (0,a,b,c,-d,-e,-f,g)        # 'antiparallel face diagonals'

# Use sympy for symbolic / exact computation
import itertools

def vec(coords):
    return np.array(coords, dtype=int)

# Halcke (a=44,b=117,c=240; not a PCP, just an Euler brick)
v1 = vec((0, a, b, c, d, e, f, 0))  # ignore g since it's not integer
print(f"\nHalcke (non-PCP): v1 = {v1}")
print(f"  N(v1) = {(v1*v1).sum()} = expected {(a*a+b*b+c*c+d*d+e*e+f*f)}")

# Now construct a HYPOTHETICAL PCP and compute Gram matrix:
print("\n--- Hypothetical PCP analysis ---")
print("Pretend (a,b,c,d,e,f,g) = (a,b,c,d,e,f,g) and compute Gram matrices symbolically.")

# We use symbolic via sympy:
from sympy import symbols, simplify, Matrix, sqrt, expand
sa, sb, sc, sd, se, sf, sg = symbols('a b c d e f g', positive=True)

# Constraint substitutions:
constraint_subs = {
    sd**2: sa**2 + sb**2,
    se**2: sb**2 + sc**2,
    sf**2: sa**2 + sc**2,
    sg**2: sa**2 + sb**2 + sc**2,
}

# Brick vector v0 in R^8 with x_0=0:
v0 = Matrix([0, sa, sb, sc, sd, se, sf, sg])
N0 = (v0.T @ v0)[0]
print(f"N(v0) = a^2+b^2+c^2+d^2+e^2+f^2+g^2")
N0_reduced = N0.subs(constraint_subs)
print(f"     = {expand(N0_reduced)} = 4 g^2 (under constraints)")

# Octonion conjugate: x-bar = -x for pure imaginary, so x x-bar = N(x).
# Now consider some 'derived' vectors:

# w1 = v0 (the brick itself)
# w2 = (0, -a, -b, -c, d, e, f, g) (negate edges)
# w3 = (0, a, b, c, -d, -e, -f, g) (negate face diagonals)
# w4 = (0, a, b, c, d, e, f, -g)  (negate space diagonal)
# These are all candidate E_8 vectors of squared norm 4g^2.

w1 = Matrix([0, sa, sb, sc, sd, se, sf, sg])
w2 = Matrix([0, -sa, -sb, -sc, sd, se, sf, sg])
w3 = Matrix([0, sa, sb, sc, -sd, -se, -sf, sg])
w4 = Matrix([0, sa, sb, sc, sd, se, sf, -sg])

vectors = [w1, w2, w3, w4]
n = len(vectors)
gram = Matrix.zeros(n, n)
for i in range(n):
    for j in range(n):
        ip = (vectors[i].T @ vectors[j])[0]
        gram[i, j] = expand(ip.subs(constraint_subs))

print("\nGram matrix of (w1, w2, w3, w4) under PCP constraints:")
for i in range(n):
    row = []
    for j in range(n):
        row.append(str(gram[i,j]))
    print("  [" + ", ".join(row) + "]")

print("\nDiagonal entries (norms):")
for i in range(n):
    print(f"  N(w_{i+1}) = {gram[i,i]}")
print(f"\nDeterminant of Gram:")
print(f"  det = {expand(gram.det())}")
